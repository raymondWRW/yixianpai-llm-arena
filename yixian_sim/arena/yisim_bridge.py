"""yisim_bridge — run battles through the open-source yisim engine (bun).

yisim is the arena's GROUND TRUTH combat engine (user decision, 2026-09-16):
unlike the Oracle it prints a full turn-by-turn log, so LLM bots can study
exactly why a battle went the way it did. Input format (just_run.js stdin):

    {"a_first": bool,
     "a": {"character": "sw1", "cultivation": N, "hp": maxhp, "destiny": N,
           "physique": N, "max_physique": N, "cards": ["sword slash 3", ...]},
     "b": {...}}

Cards are passed as lowercase ENGLISH names + level (fuzzy-matched by yisim).
"""
