_name_cache = None


def _names():
    """game card_id -> yisim input string ('english name N'), for every level."""
    global _name_cache
    if _name_cache is None:
        raw = json.loads(_CARDS_JSON.read_text(encoding="utf-8"))
        items = raw if isinstance(raw, list) else raw.values()
        m = {}
        for c in items:
            cid, en, lv = c.get("card_id"), c.get("name_en"), c.get("level")
            if cid and en and lv:
                m[int(cid)] = f"{en.lower()} {lv}"
        _name_cache = m
    return _name_cache


def card_to_yisim(cid: int) -> str:
    n = _names().get(int(cid))
    if not n:
        raise KeyError(f"card {cid} has no yisim name (season/unknown card?)")
    return n


_fieldable_cache = None


def _fieldable():
    """Base card ids yisim implements in combat (yisim_fieldable.json is
    generated by resolving every card through yisim's own fuzzy matcher and
    keeping exact/verified-alt matches; herbs, elixirs, [置换] utility cards
    and pseudo-cards are blocked — they are economy-only)."""
    global _fieldable_cache
    if _fieldable_cache is None:
        data = json.loads((Path(__file__).resolve().parent /
                           "yisim_fieldable.json").read_text(encoding="utf-8"))
        _fieldable_cache = (set(data["fieldable"]),
                            {int(k): v for k, v in data["blocked"].items()})
    return _fieldable_cache


_kw_cache = None


def limited_kw(cid: int) -> list:
    """[消耗]/[持续] keywords on this exact card (board legality: a board may
    hold at most 2 such cards — user rule 2026-09-17)."""
    global _kw_cache
    if _kw_cache is None:
        raw = json.loads(_CARDS_JSON.read_text(encoding="utf-8"))
        items = raw if isinstance(raw, list) else raw.values()
        _kw_cache = {}
        for c in items:
            d = c.get("desc_cn") or ""
            _kw_cache[int(c["card_id"])] = [k for k in ("消耗", "持续")
                                            if f"[{k}]" in d]
    return _kw_cache.get(int(cid), [])


def _combat_name(cid: int) -> str:
    if not combat_ok(cid):
        raise ValueError(f"card {card_to_yisim(cid)!r} ({cid}) has no yisim "
                         f"combat implementation (economy-only card)")
    return card_to_yisim(cid)


def combat_ok(cid: int) -> bool:
    fieldable = _fieldable()[0]
    base = int(cid)
    for _ in range(4):                  # strip the +10000/level encoding
        if base in fieldable:
            return True
        base -= 10000
    return False


def player_payload(char_id: int, cultivation: int, max_hp: int, destiny: int,
                   cards: list, physique: int = 0, max_physique: int = 0,
                   round_number: int = 1, extra: dict = None) -> dict:
    out = {
        "character": CHAR_KEYS[int(char_id)],
        "round_number": int(round_number),   # drives the destiny formula
        "cultivation": int(cultivation),
        # 生命转化 (user rule): every 体魄 point adds +1 max HP. yisim computes
        # max_hp = hp + physique, which IS that rule — pass base hp unadjusted.
        "hp": int(max_hp),
        "destiny": int(destiny),
        "physique": int(physique), "max_physique": int(max_physique),
        "cards": [_combat_name(c) for c in cards if c],
    }
    if extra:
        out.update({k: int(v) for k, v in extra.items()})
    return out


def run_battle(a: dict, b: dict, a_first: bool = True, timeout: int = 60) -> dict:
    """Run one battle (via the warm batch runner: gets per-turn STATE lines).
    Returns {winner: 'a'|'b'|None, destiny_loss, loser, destiny_after, turns,
    final_physique, log}. `a`/`b` from player_payload()."""
    r = run_battles([(a, b, a_first)], want_log=True, timeout=timeout)[0]
    if "error" in r:
        raise RuntimeError(f"yisim failed: {r['error'][:400]}")
    return r


def humanize_log(log: str, name_a: str, name_b: str) -> str:
    """Rewrite yisim's 'player 0/1' with real names. yisim swaps its player
    array every b-turn, so 'player 0' is always the CURRENT ACTOR: inside a
    'turn Na' block player0 = seat A; inside 'turn Nb' player0 = seat B;
    outside turn blocks (setup, final result) player0 = seat A."""
    out = []
    p0, p1 = name_a, name_b
    for line in log.splitlines():
        m = re.match(r"turn \d+([ab]) begins", line)
        if m:
            p0, p1 = ((name_a, name_b) if m.group(1) == "a"
                      else (name_b, name_a))
        out.append(line.replace("player 0", p0).replace("Player 0", p0)
                       .replace("player 1", p1).replace("Player 1", p1))
        if re.match(r"turn \d+[ab] ends", line):
            p0, p1 = name_a, name_b
    return "\n".join(out)


def run_battles(battles: list, want_log: bool = False,
                timeout: int = 600) -> list:
    """Batch: many battles in ONE warm bun process (batch_run.js).
    `battles` = [(a, b, a_first), ...]; returns list of result dicts in the
    same shape as run_battle (log only when want_log)."""
    payload = "\n".join(
        json.dumps({"battle": {"a_first": bool(f), "a": a, "b": b},
                    "want_log": bool(want_log)})
        for a, b, f in battles)
    proc = subprocess.run([BUN, "batch_run.js"], input=payload.encode("utf-8"),
                          capture_output=True, cwd=str(YISIM_DIR),
                          timeout=timeout)
    if proc.returncode != 0:
        raise RuntimeError("yisim batch failed: "
                           + proc.stderr.decode("utf-8", "replace")[:400])
    out = []
    for line in proc.stdout.decode("utf-8", "replace").splitlines():
        if line.strip():
            out.append(json.loads(line))
    if len(out) != len(battles):
        raise RuntimeError(f"batch returned {len(out)}/{len(battles)} results")
    return out


def _final_physique(log: str) -> dict:
    """Battle-end physique per side (跨回合保留: physique persists between
    battles, clamped to the retention cap by the engine). Attributed by turn
    block, since yisim labels the current actor 'player 0' in its own turn."""
    phys = {"a": None, "b": None}
    side = None
    for line in log.splitlines():
        m = re.match(r"turn \d+([ab]) begins", line)
        if m:
            side = m.group(1)
            continue
        m = re.search(r"[Nn]ow have (-?\d+) physique", line)
        if m and side:
            phys[side] = int(m.group(1))
    return phys


def qi_stall_count(log: str, side: str) -> int:
    """Referee helper: how many turns a side burned on the +1-qi default action.
    yisim logs 'gained 1 qi to afford ...' style lines; count per side is
    approximated by counting the marker lines (both sides combined is fine for
    a red-flag check)."""
    return len(re.findall(r"to afford|can't afford|gains 1 qi and ends", log))
